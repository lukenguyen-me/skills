#!/usr/bin/env python3
"""Keep Claude Code role agents in step with the Luke Mode models file.

write  generates luke-reasoning, luke-coding, luke-worker, and luke-reviewer
       agent definitions from the models file's `Claude Code` profile.
check  reports role agents that are missing or disagree with the profile.
hook   is the PreToolUse handler for the Agent tool, registered by the skill's
       frontmatter. Once Luke Mode is invoked, it denies spawns that leave the
       configured role models: forks, non-role agent types, and model overrides
       that differ from the profile.

The models file stays the source of truth; agent files are generated output.
"""

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROLES = ('Reasoning', 'Coding', 'Worker', 'Reviewer')
HEADING = 'Claude Code'
GENERATED = '# Generated by luke-mode setup. Edit the models file and rerun setup.'
READ_ONLY_TOOLS = 'Read, Grep, Glob, Bash'

SPECS = {
    'Reasoning': {
        'description': 'Luke Mode Reasoning role. Use for every Reasoning task in a Luke '
                       'Mode run: architecture, complex debugging, consequential trade-offs, '
                       'and causal investigation.',
        'tools': READ_ONLY_TOOLS + ', WebFetch, WebSearch',
        'work': 'Analyze and recommend. Use Bash for read-only commands and existing checks '
                'that reproduce behavior; leave project files unchanged.',
    },
    'Coding': {
        'description': 'Luke Mode Coding role. Use for every Coding task in a Luke Mode run: '
                       'features, fixes, refactors, tests, and edits inside a bounded brief.',
        'disallowed': 'Agent',
        'work': 'Make the change the brief asks for, with its tests. Run the verification '
                'the brief names plus focused tests for what you changed. Preserve changes '
                'you did not make.',
    },
    'Worker': {
        'description': 'Luke Mode Worker role. Use for every Worker task in a Luke Mode run: '
                       'read-only lookups whose answer is a location or fact, such as files, '
                       'symbols, call sites, and config values.',
        'tools': READ_ONLY_TOOLS,
        'work': 'Find and report the facts the brief asks for, with file and line locations. '
                'Use Bash for read-only commands; leave project files unchanged. When the '
                'answer needs judgment, report it as ambiguous instead of guessing.',
    },
    'Reviewer': {
        'description': 'Luke Mode Reviewer role. Use for every Reviewer task in a Luke Mode '
                       'run: independent code review and evidence checks on a stable snapshot.',
        'tools': READ_ONLY_TOOLS,
        'work': 'Review the snapshot the brief names against its requirements and project '
                'standards. Use Bash for read-only commands and existing checks; leave project '
                'files unchanged. Rank findings by severity, each with a location, its '
                'consequence, and supporting evidence.',
    },
}


class ProfileError(Exception):
    pass


def agent_name(role):
    return f'luke-{role.lower()}'


def parse_profile(text):
    """Return {role: (model, effort)} from the Claude Code section, or None."""
    section = re.search(rf'^##\s+{re.escape(HEADING)}\s*$(.*?)(?=^##\s|\Z)', text, re.M | re.S)
    if not section:
        return None
    profile = {}
    for line in section.group(1).splitlines():
        cells = [c.strip().strip('*`').strip() for c in line.strip().strip('|').split('|')]
        role = cells[0].capitalize()
        if len(cells) >= 3 and role in ROLES:
            profile[role] = (cells[1].lower(), cells[2].lower() or 'inherit')
    missing = [r for r in ROLES if r not in profile]
    if missing:
        raise ProfileError(f"the {HEADING} profile lacks roles: {', '.join(missing)}")
    return profile


def render(role, model, effort):
    spec = SPECS[role]
    lines = ['---', f'name: {agent_name(role)}', f"description: {json.dumps(spec['description'])}",
             f'model: {model}']
    if effort != 'inherit':
        lines.append(f'effort: {effort}')
    if 'tools' in spec:
        lines.append(f"tools: {spec['tools']}")
    if 'disallowed' in spec:
        lines.append(f"disallowedTools: {spec['disallowed']}")
    lines += [GENERATED, '---', '']
    lines += [
        f'You are the {role} role in a Luke Mode run. The parent agent orchestrates; '
        'your brief is the whole task, and you cannot load Luke Mode yourself.',
        '',
        f"- {spec['work']}",
        '- Stay inside the brief: its scope, owning directory, and permitted writes. '
        'Report work outside it as a gap for the parent.',
        '- Do the work yourself, in this context.',
        '- End with findings plus gaps: what you did or found, what you verified and how, '
        'what you did not verify, and open questions or risks. A claim without evidence '
        'is a gap.',
        '',
    ]
    return '\n'.join(lines)


def frontmatter_value(text, key):
    match = re.search(rf'^{key}:\s*(.+?)\s*$', text.split('\n---', 1)[0], re.M)
    return match.group(1) if match else None


def load(models_path):
    path = Path(models_path).expanduser()
    profile = parse_profile(path.read_text())
    if profile is None:
        raise ProfileError(f'{path} has no "## {HEADING}" profile')
    return profile


def drift(profile, paths, exact=True, roles=ROLES):
    """Return one message per role agent file that is missing or stale.

    paths maps each role to its definition file. exact compares the whole file;
    otherwise only the model and effort the profile sets.
    """
    problems = []
    for role in roles:
        target, (model, effort) = paths[role], profile[role]
        if not target.exists():
            problems.append(f'{target}: missing')
            continue
        text = target.read_text()
        if exact:
            stale = text != render(role, model, effort)
        else:
            stale = (frontmatter_value(text, 'model') != model
                     or (frontmatter_value(text, 'effort') or 'inherit') != effort)
        if stale:
            problems.append(f'{target}: differs from the {role} profile '
                            f'(model {model}, effort {effort})')
    return problems


def in_dir(dest):
    return {role: Path(dest).expanduser() / f'{agent_name(role)}.md' for role in ROLES}


def cmd_write(args):
    profile = load(args.models)
    dest = Path(args.dest).expanduser()
    foreign = [p for p in (dest / f'{agent_name(r)}.md' for r in ROLES)
               if p.exists() and GENERATED not in p.read_text()]
    if foreign and not args.force:
        raise ProfileError('not generated by luke-mode setup, left unchanged: '
                           + ', '.join(map(str, foreign)) + ' (rerun with --force to replace)')
    dest.mkdir(parents=True, exist_ok=True)
    for role in ROLES:
        target = dest / f'{agent_name(role)}.md'
        target.write_text(render(role, *profile[role]))
        print(f'{target}: {role} -> model {profile[role][0]}, effort {profile[role][1]}')


def cmd_check(args):
    profile, dest = load(args.models), in_dir(args.dest)
    problems = drift(profile, dest)
    # A project agent overrides a personal one by name, so check what Claude Code loads.
    loaded = resolve(args.cwd, Path.home())[1]
    shadows = {r: p for r, p in loaded.items() if p != dest[r] and p.exists()}
    problems += [f'{problem}; it overrides {dest[role]}'
                 for role in shadows for problem in drift({role: profile[role]}, shadows, exact=False, roles=(role,))]
    for problem in problems:
        print(problem)
    if problems:
        return 1
    print('role agents match the profile')
    return 0


# --- PreToolUse hook -------------------------------------------------------

def repo_root(cwd):
    result = subprocess.run(['git', '-C', cwd, 'rev-parse', '--show-toplevel'],
                            capture_output=True, text=True)
    return Path(result.stdout.strip()) if result.returncode == 0 else None


def resolve(project_dir, home):
    """Return (models path or None, role -> agent file Claude Code loads).

    The models file follows references/models.md: the repository file first,
    then the personal one. A project agent overrides a personal one by name.
    """
    root = repo_root(project_dir)
    project = root / '.claude' / 'agents' if root else None
    agents = {}
    for role, personal_agent in in_dir(home / '.claude' / 'agents').items():
        project_agent = project / personal_agent.name if project else None
        agents[role] = project_agent if project_agent and project_agent.exists() else personal_agent
    for models in ((root / '.luke-mode' / 'models.md') if root else None,
                   home / '.config' / 'luke-mode' / 'models.md'):
        if models and models.exists():
            return models, agents
    return None, agents


def decide(tool_input, project_dir, home):
    """Return a denial reason, or None to let the Agent call through."""
    models, agents = resolve(project_dir, home)
    if models is None:
        return None
    try:
        profile = parse_profile(models.read_text())
    except ProfileError as error:
        return f'Luke Mode cannot route this delegate: {models}: {error}. Configure it with /luke-mode setup.'
    if profile is None:
        return None

    agent_type = tool_input.get('subagent_type') or 'general-purpose'
    model, effort = tool_input.get('model'), tool_input.get('effort')
    roster = ', '.join(agent_name(r) for r in ROLES)
    if agent_type == 'fork':
        return f'Luke Mode: a fork runs on the parent model. Spawn the role agent instead: {roster}.'

    problems = drift(profile, agents, exact=False)
    role = next((r for r in ROLES if agent_name(r) == agent_type), None)
    if role:
        if problems:
            return ('Luke Mode role agents disagree with the models file '
                    f'({models}): ' + '; '.join(problems)
                    + '. Stop delegating and ask the user to run /luke-mode setup.')
        want, want_effort = profile[role]
        if model and (want == 'inherit' or model != want):
            return (f'Luke Mode: {agent_type} runs model {want} from {models}. '
                    'Omit the model parameter so the role agent applies it.')
        if effort and (want_effort == 'inherit' or effort != want_effort):
            return (f'Luke Mode: {agent_type} runs effort {want_effort} from {models}. '
                    'Omit the effort parameter so the role agent applies it.')
        return None

    if not any(path.exists() for path in agents.values()):
        # No role agents installed: the general-purpose fallback needs an explicit role model.
        # An omitted model inherits the parent, which only an `inherit` role asks for.
        models_set = {m for m, _ in profile.values()}
        if model in models_set or (model is None and 'inherit' in models_set):
            return None
        allowed = ', '.join(sorted(models_set - {'inherit'}))
        return (f'Luke Mode: pass model set to the role\'s profile model ({allowed}) '
                f'from {models}. Run /luke-mode setup to install the role agents.')
    return (f'Luke Mode routes every delegate to a role agent. Spawn one of: {roster}, '
            f'chosen by the task\'s role. {agent_type} is outside the roster. Routing stays '
            'strict for the rest of this session; for work outside the Luke Mode task, tell '
            'the user that a new session lifts it.')


def cmd_hook(_args):
    try:
        data = json.load(sys.stdin)
        if data.get('tool_name') != 'Agent':
            return 0
        # Claude Code loads agents from the session's project, wherever the shell has moved.
        project_dir = os.environ.get('CLAUDE_PROJECT_DIR') or data.get('cwd') or '.'
        reason = decide(data.get('tool_input') or {}, project_dir, Path.home())
    except Exception as error:  # A broken hook must not block delegation.
        print(f'role_agents hook skipped: {error}', file=sys.stderr)
        return 0
    if reason:
        print(json.dumps({'hookSpecificOutput': {
            'hookEventName': 'PreToolUse',
            'permissionDecision': 'deny',
            'permissionDecisionReason': reason,
        }}))
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    sub = parser.add_subparsers(dest='command', required=True)
    for name in ('write', 'check'):
        p = sub.add_parser(name)
        p.add_argument('--models', required=True, help='Luke Mode models file')
        p.add_argument('--dest', required=True, help='agents directory: ~/.claude/agents or <repo>/.claude/agents')
        p.add_argument('--cwd', default='.', help='project whose .claude/agents may override --dest')
        if name == 'write':
            p.add_argument('--force', action='store_true', help='replace hand-written role agent files')
    sub.add_parser('hook')
    args = parser.parse_args()
    try:
        return {'write': cmd_write, 'check': cmd_check, 'hook': cmd_hook}[args.command](args) or 0
    except (ProfileError, OSError) as error:
        print(f'role_agents: {error}', file=sys.stderr)
        return 2 if args.command != 'hook' else 0


if __name__ == '__main__':
    sys.exit(main())
